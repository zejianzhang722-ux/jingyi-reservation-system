const assert = require('node:assert/strict')
const { selectionAtPoint } = require('../miniapp/components/timeline/selection')
assert.deepEqual(selectionAtPoint(8, 23, 300, { left: -100, width: 600 }), { start: 18, end: 19 })
assert.deepEqual(selectionAtPoint(8, 23, 150, { left: -50, width: 300 }), { start: 18, end: 19 })
assert.deepEqual(selectionAtPoint(8, 10, 999, { left: 0, width: 100 }), { start: 9.5, end: 10 })
assert.deepEqual(selectionAtPoint(8, 10, -1, { left: 0, width: 100 }), { start: 8, end: 9 })
assert.deepEqual(selectionAtPoint(9.5, 10, undefined, null), { start: 9.5, end: 10 })
assert.equal(selectionAtPoint(10, 10, 50, { left: 0, width: 100 }), null)
assert.equal(selectionAtPoint(NaN, 12, 50, { left: 0, width: 100 }), null)
assert.deepEqual(selectionAtPoint(14.7, 17, 0, { left: 0, width: 100 }), { start: 15, end: 16 })
assert.equal(selectionAtPoint(14.7, 15.2, 0, { left: 0, width: 100 }), null)
console.log('PASS: timeline tap matches rendered time across screen sizes and scroll offsets')
