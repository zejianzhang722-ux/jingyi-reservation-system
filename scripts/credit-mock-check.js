const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
process.env.MOCK_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'jingyi-credit-check-'));
const mock = require('../server/src/config/mock-db');
const dbPath = require.resolve('../server/src/config/database');
require.cache[dbPath] = { id: dbPath, filename: dbPath, loaded: true, exports: { isMock: () => true, query: mock.query } };
const credit = require('../server/src/services/creditService');
const userController = require('../server/src/controllers/userController');
const tables = mock.__tables;
(async () => {
  tables.users = [{ id: 1, credit_score: 119, status: 'active' }];
  tables.credits_log = [];
  tables.notifications = [];
  await credit.addCredit(1, 5, 'good_behavior', '正常使用');
  assert.equal(Number(tables.users[0].credit_score), 120);
  assert.equal(Number(tables.credits_log[0].score_change), 1);
  await credit.addCredit(1, -61, 'violation', '违规扣分');
  assert.equal(tables.users[0].status, 'active');
  const until = String(tables.users[0].restricted_until);
  await credit.addCredit(1, 0, 'reward', '分数未变');
  assert.equal(String(tables.users[0].restricted_until), until);
  await credit.addCredit(1, -30, 'violation', '违规扣分');
  assert.equal(tables.users[0].status, 'active');
  const count = tables.credits_log.length;
  const first = await credit.addCreditWithinTransaction({ query: mock.query }, 1, -20, 'noshow', '爽约', { reservationId: 99, dedupeKey: 'noshow:99' });
  const repeat = await credit.addCreditWithinTransaction({ query: mock.query }, 1, -20, 'noshow', '爽约', { reservationId: 99, dedupeKey: 'noshow:99' });
  assert.equal(first.change, -20);
  assert.equal(repeat.idempotent, true);
  assert.equal(tables.credits_log.length, count + 1);
  tables.users[0].restricted_until = '2020-01-01 00:00:00';
  await credit.checkAndRestoreUsers();
  assert.equal(tables.users[0].status, 'active');
  await credit.addCredit(1, -20, 'violation', '违规扣分');
  assert.equal(Number(tables.users[0].credit_score), 0);
  assert.equal(Number(tables.credits_log.at(-1).score_change), -9);
  let body;
  await userController.getCredit({ user: { id: 1 } }, { status() { return this; }, json(value) { body = value; } });
  assert.equal(body.data.creditScore, 0);
  assert.equal(body.data.records[0].score_after, 0);
  assert.equal(body.data.rules.maxScore, 120);
  console.log('PASS: real mock score bounds, threshold state changes, expiry recovery, reservation penalty deduplication, credit API snapshots');
  console.log('Isolated mock directory: ' + process.env.MOCK_DATA_DIR);
})().catch(err => { console.error(err); process.exitCode = 1; });
