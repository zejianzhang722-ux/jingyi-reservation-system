const assert = require('assert/strict');
const fs = require('fs'), os = require('os'), path = require('path');
process.env.MOCK_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'jingyi-dance-changes-'));
const mock = require('../server/src/config/mock-db');
const dbPath = require.resolve('../server/src/config/database');
require.cache[dbPath] = { id: dbPath, filename: dbPath, loaded: true, exports: { isMock: () => true, query: mock.query, getConnection: async () => ({ query: mock.query, release() {} }) } };
const tables = mock.__tables;
const emitted = [];
require('../server/src/services/realtimeEventService').setIO({ to(room) { return { emit(event, payload) { emitted.push({room,event,payload}); } }; } });
const service = require('../server/src/services/danceGroupNotificationService');
const mutation = require('../server/src/services/reservationMutationService');
const date = require('../server/src/utils/helpers').formatDate(new Date(Date.now() + 86400000));
tables.admins = [{ id: 1, role: 'dorm_manager', scope_type: 'building', building_id: 3, status: 'active' }];
tables.admin_notifications = [];
tables.reservations = [{ id: 90001, user_id: 1, room_id: 14, date, start_time: '17:00', end_time: '18:00', participants: 2, purpose: '排练', status: 'approved' }];
tables.reservation_groups = [{ id: 90002, reservation_id: 90001, room_id: 14, created_by: 1, max_members: 2, name: '排练', status: 'approved' }];
tables.reservation_group_members = [{ group_id: 90002, user_id: 1, status: 'confirmed' }];
tables.reservation_slots = [];
(async () => {
  await service.notifyApproved(90001);
  await mutation.updateReservation({ reservationId: 90001, actor: { id: 1, role: 'student' }, startTime: '18:00', endTime: '19:00' });
  assert.equal(tables.admin_notifications.length, 2, 'editing approved dance booking immediately corrects administrator notice');
  assert.ok(tables.admin_notifications[1].content.includes('更新') && tables.admin_notifications[1].content.includes('18:00'));
  await Promise.all(Array.from({ length: 20 }, () => service.notifyApproved(90001)));
  assert.equal(tables.admin_notifications.length, 2, 'changed time is deduplicated');
  await mutation.updateReservation({ reservationId: 90001, actor: { id: 1, role: 'student' }, startTime: '17:00', endTime: '18:00' });
  assert.equal(tables.admin_notifications.length, 3, 'reverting time still creates a fresh correction');
  tables.reservations[0].status = 'checked_in';
  tables.checkins = [{ id: 1, reservation_id: 90001, user_id: 1, room_id: 14, checkout_time: null }];
  const res = { status(code) { this.code = code; return this; }, json(body) { this.body = body; return this; } };
  await require('../server/src/controllers/checkinController').checkout({ body: { reservationId: 90001 }, user: { id: 1, role: 'student' } }, res);
  assert.equal(res.code, 200, JSON.stringify(res.body));
  assert.equal(tables.admin_notifications.filter(n => n.type === 'dance_group_released').length, 1, 'early checkout immediately releases team occupancy notice');
  await service.reconcile(new Date());
  assert.equal(tables.admin_notifications.filter(n => n.type === 'dance_group_released').length, 1);
  tables.admins.push({ id: 2, role: 'admin', scope_type: 'building', building_id: 3, status: 'active' });
  await service.notifyReleased(90001);
  assert.equal(tables.admin_notifications.filter(n => Number(n.admin_id) === 2).length, 0, 'no release notice to an admin who never received the occupancy notice');
  assert.ok(emitted.filter(e => e.event === 'notification').every(e => e.room === 'admin:1'), 'all notification pushes remain isolated fake administrator channels');
  console.log('PASS: time correction, 20-way changed-time dedupe, reverted time, checkout release, recovery dedupe, previous-recipient-only release');
})().catch(err => { console.error(err); process.exitCode = 1; });
