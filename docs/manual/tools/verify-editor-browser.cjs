const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {chromium}=require('D:/工青协/volunteer-platform/.tools/browser-qa/node_modules/playwright-core');
const {createServer}=require('./serve-editor.cjs');
(async()=>{
  const root=path.resolve(__dirname,'..');
  const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'jingyi-browser-editor-test-'));
  const layoutFile=path.join(scratch,'annotation-layouts.js');
  fs.copyFileSync(path.join(root,'annotation-layouts.js'),layoutFile);
  const server=createServer(root,layoutFile);
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--disable-gpu']});
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const manual=await context.newPage(),editor=await context.newPage();
  const errors=[];for(const page of [manual,editor])page.on('pageerror',e=>errors.push(e.message));
  try{
    await manual.goto(base+'/index.html#/student/room-list');
    await editor.goto(base+'/tools/annotation-editor.html#/student/room-list');
    await editor.locator('.edit-box').first().waitFor();
    const alignment=await manual.evaluate(()=>{
      const img=document.querySelector('.screen-image'),stage=img.parentElement,box=stage.querySelector('.annotation');
      const imageRect=img.getBoundingClientRect(),stageRect=stage.getBoundingClientRect(),boxRect=box.getBoundingClientRect();
      return {imageHeight:imageRect.height,stageHeight:stageRect.height,actualTop:boxRect.top-imageRect.top,expectedTop:Number(box.dataset.y)/img.naturalHeight*imageRect.height,src:img.currentSrc};
    });
    const editorSrc=await editor.locator('#screenImage').evaluate(img=>img.currentSrc);
    assert.equal(alignment.src,editorSrc,'资料库与校准器使用了不同截图文件');
    assert(Math.abs(alignment.imageHeight-alignment.stageHeight)<1,'资料库标注层高度没有跟随完整截图');
    assert(Math.abs(alignment.actualTop-alignment.expectedTop)<1,'资料库标注框没有落在校准器对应的截图像素位置');
    const before=await manual.locator('.annotation').first().getAttribute('data-x');
    const beforeWidth=await editor.locator('#coordW').inputValue();
    const beforeHeight=await editor.locator('#coordH').inputValue();
    await editor.locator('.edit-box').first().focus();
    await editor.keyboard.press('ArrowRight');
    const handle=editor.locator('.edit-box').first().locator('.resize-handle');
    await handle.scrollIntoViewIfNeeded();
    const rect=await handle.boundingBox();
    await editor.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);
    await editor.mouse.down();
    await editor.mouse.move(rect.x+rect.width/2+20,rect.y+rect.height/2+10,{steps:4});
    await editor.mouse.up();
    assert(Number(await editor.locator('#coordW').inputValue())>Number(beforeWidth),'拖动右下角未能调整标注宽度');
    await editor.locator('#save').click();
    await editor.locator('.status.ok').waitFor();
    await manual.waitForFunction(x=>document.querySelector('.annotation')?.dataset.x===String(Number(x)+1),before);
    await manual.reload();
    assert.equal(await manual.locator('.annotation').first().getAttribute('data-x'),String(Number(before)+1),'重新打开后标注未保留');
    await editor.locator('#coordX').fill(before);
    await editor.locator('#coordX').dispatchEvent('change');
    await editor.locator('#coordW').fill(beforeWidth);
    await editor.locator('#coordW').dispatchEvent('change');
    await editor.locator('#coordH').fill(beforeHeight);
    await editor.locator('#coordH').dispatchEvent('change');
    await editor.locator('#save').click();
    await editor.locator('.status.ok').waitFor();
    assert.equal(errors.length,0,errors.join('\n'));
  }finally{await browser.close();await new Promise(resolve=>server.close(resolve));if(!path.resolve(scratch).startsWith(path.resolve(os.tmpdir())+path.sep))throw Error('临时测试目录位置异常');fs.rmSync(scratch,{recursive:true,force:true});}
  console.log('PASS: 校准器拖动缩放、键盘调整、保存、手册实时同步与刷新保留');
})().catch(e=>{console.error(e);process.exitCode=1});
